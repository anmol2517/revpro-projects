//  Addition Assignment Operators
let x = 11;
x += 4;
console.log(x);   // 15


//  Subtraction Assignment Operators
let y = 11;
y -= 4;
console.log(y);   //  7


//  Multiplication Assignment Operators
let a = 11;
a *= 4;
console.log(a);   //  44


//  Division Assignment Operators
let b = 11;
b /= 4;
console.log(b);   //  2.75


//  Remainder Assignment Operators
let c = 11;
c %= 4;
console.log(c);   //  3 


//  Exponentiation Assignment Operators
let d = 11;
d **= 4;
console.log(d);   //  14641


//  Logical AND Assignment Operators
let f = true;
f &&= false;
console.log(f);   //  false


//  Logical OR Assignment Operators
let g = false;
g ||= true;
console.log(g);   //  true


//  Comparison Assignment Operators
let h = 5;
h ??= 10;
console.log(h);   //  5


// Floor Division Assignment Operators
let e = 11;
e =// 4;      // ---------------- "//" comement symbol is used to indicate floor division
console.log(e);   //  2


// Equal to Assignment Operators
let u = 35;
let v = 39;
console.log(u<v);  // true


// Not Equal to Assignment Operators
let m = 25;
let n = 30;
console.log(m!=n);  // true


// Strict Equal to Assignment Operators
let p = 45;
let q = 37;
console.log(p===q);  // false


let s = 45;
let z = 45;
console.log(s==z);  // true