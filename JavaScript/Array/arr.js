//  PUSH - ADD Element at the END of the ARRAY

const animal = ["Dog", "Elephant", "Lion", "Tiger"];
console.log(animal);

animal.push("Cat");
console.log(animal);

console.log("-------------------------------------");

// POP Remove Last Element 

const team = ["CSK", "MI", "KXIP", "SRH", "DC"];
console.log(team);

team.pop();
console.log(team);

console.log("-------------------------------------");

// SHIFT Remove First Element

const currency = ["Dollar", "Rupee", "Rubel", "Euro"];
console.log(currency);

currency.shift();
console.log(currency);

console.log("-------------------------------------"); 

// UNSHIFT Add Element at Beginning of the Array

const laptop = ["HP", "DELL", "ASUS", "SAMSUNG"];
console.log(laptop);

laptop.unshift("APPLE");
console.log(laptop);

console.log("-------------------------------------"); 

// SORT FUNCTION ARRAY  -  sort()

const branch = ["CSE", "IT", "ECE", "AIML", "Civil"];
console.log(branch);

branch.sort();
console.log(branch);

console.log("-------------------------------------"); 

// REVERSE FUNCTION ARRAY  -  reverse()

const job = ["Tech", "Sales", "Bpo", "Marketing"];
console.log(job);

job.reverse();
console.log(job);

console.log("-------------------------------------"); 

const num1 = [25, 99, 73, 33, 57];
num1.sort();
console.log(num1);

num1.reverse();
console.log(num1);

console.log("-------------------------------------"); 
