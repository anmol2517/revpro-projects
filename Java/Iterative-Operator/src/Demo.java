public class Demo {
    public static void main(String[] args){
        int n = 5;

        while(n <= 11) {
            System.out.println(n);
            n++;
        }
        System.out.println("-----------");

        int i = 10;
        do{
            System.out.println(i + " ");
            i--;
        } while (i >= 6);
    }
}

